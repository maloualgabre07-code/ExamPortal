const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('fs');const path=require('path');
const {createApp}=require('../app');const {testPool}=require('./test-db');
test('Open instructor signup, student class-code joining, code rotation and assigned-exam access',async t=>{
 const pool=await testPool();await pool.exec(fs.readFileSync(path.join(__dirname,'../schema.sql'),'utf8'));
 const service=createApp(pool,'test-session-secret-longer-than-thirty-two',{}, {inviteCode:'test-invitation-code-123456789'});
 const server=service.app.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
 t.after(async()=>{service.close();await new Promise(r=>server.close(r));await pool.end();});
 const base=`http://127.0.0.1:${server.address().port}/api`;let cookie='',csrf='';
 async function call(url,method='GET',body){const r=await fetch(base+url,{method,headers:{Cookie:cookie,...(method!=='GET'?{'Content-Type':'application/json','X-CSRF-Token':csrf}:{})},...(method!=='GET'?{body:JSON.stringify(body)}:{})});if(r.headers.get('set-cookie'))cookie=r.headers.get('set-cookie').split(';')[0];const d=await r.json();if(d.token)csrf=d.token;return{status:r.status,...d};}
 await call('/csrf');const body={full_name:'New Teacher',email:'new@example.com',password:'TeacherPass123!',role:'instructor'};
 assert.equal((await call('/register','POST',{...body,role:'admin'})).status,400);
 assert.equal((await call('/register','POST',body)).status,201);
 assert.equal((await call('/login','POST',{email:body.email,password:body.password})).user.role,'instructor');
 assert.equal((await call('/users')).status,403);
 const cl=(await call('/classes','POST',{name:'Web Development',description:''})).class;
 assert.match(cl.join_code,/^[A-F0-9]{16}$/);
 const exam=(await call('/exams','POST',{title:'Class Exam',description:'',duration_minutes:5,passing_score:50,max_attempts:1})).exam;
 assert.equal((await call(`/exams/${exam.id}/questions`,'POST',{prompt:'Is HTML markup?',question_type:'true_false',options:['True','False'],correct_index:0,points:1})).status,201);
 assert.equal((await call(`/exams/${exam.id}/status`,'POST',{status:'published'})).status,400);
 assert.equal((await call(`/exams/${exam.id}/audience`,'PUT',{class_only:false,class_ids:[]})).status,400);
 assert.equal((await call(`/exams/${exam.id}/audience`,'PUT',{class_only:true,class_ids:[cl.id]})).status,200);
 assert.equal((await call(`/exams/${exam.id}/status`,'POST',{status:'published'})).status,200);
 assert.equal((await call('/register','POST',{full_name:'Student One',email:'student@example.com',password:'StudentPass123!'})).status,201);
 await call('/login','POST',{email:'student@example.com',password:'StudentPass123!'});
 assert.equal((await call('/exams')).exams.length,0);
 assert.equal((await call(`/exams/${exam.id}/start`,'POST',{})).status,403);
 const sid=(await pool.query("SELECT id FROM users WHERE email='student@example.com'")).rows[0].id;
 await pool.query('INSERT INTO class_students(class_id,student_id) VALUES($1,$2)',[cl.id,sid]);
 assert.equal((await call('/exams')).exams.length,0);
 assert.equal((await call(`/exams/${exam.id}/start`,'POST',{})).status,403);
 assert.equal((await call('/classes/join','POST',{code:'wrong'})).status,400);
 assert.equal((await call('/classes/join','POST',{code:'AAAAAAAAAAAAAAAA'})).status,404);
 assert.equal((await call('/classes/join','POST',{code:cl.join_code.toLowerCase()})).status,201);
 assert.equal((await call('/classes/join','POST',{code:cl.join_code})).status,409);
 const joined=(await call('/classes')).classes;assert.equal(joined.length,1);assert.equal(joined[0].join_code,undefined);
 assert.equal((await call('/exams')).exams[0].id,exam.id);
 assert.equal((await call(`/classes/${cl.id}/join-code`,'POST',{})).status,403);
 await call('/login','POST',{email:body.email,password:body.password});
 const rotated=await call(`/classes/${cl.id}/join-code`,'POST',{});assert.equal(rotated.status,200);assert.notEqual(rotated.join_code,cl.join_code);
 assert.equal((await call('/register','POST',{full_name:'Second Student',email:'second@example.com',password:'StudentPass123!'})).status,201);
 await call('/login','POST',{email:'second@example.com',password:'StudentPass123!'});
 assert.equal((await call('/classes/join','POST',{code:cl.join_code})).status,404);
 assert.equal((await call('/classes/join','POST',{code:rotated.join_code})).status,201);
 // The migration is safe to rerun and retains enrollment.
 await pool.exec(fs.readFileSync(path.join(__dirname,'../migrations/007-required-class-code.sql'),'utf8'));
 assert.equal((await call('/exams')).exams.length,1);
 await pool.query('DELETE FROM exam_class_assignments WHERE exam_id=$1',[exam.id]);
 await pool.query('UPDATE exams SET class_only=FALSE WHERE id=$1',[exam.id]);
 assert.equal((await call('/exams')).exams.length,0);
 assert.equal((await call(`/exams/${exam.id}/start`,'POST',{})).status,403);
 assert.equal((await pool.query('SELECT * FROM class_students')).rows.length,2);
});
